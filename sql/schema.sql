-- 在 Supabase → SQL Editor 里整体粘贴执行
create table if not exists name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result text not null,
  model_name text not null,
  created_at timestamp with time zone default now()
);

-- 允许匿名读取（给前端历史列表用）
alter table name_history enable row level security;

drop policy if exists "允许匿名读取历史" on name_history;
create policy "允许匿名读取历史"
  on name_history for select
  to anon
  using (true);

drop policy if exists "允许匿名写入历史" on name_history;
create policy "允许匿名写入历史"
  on name_history for insert
  to anon
  with check (true);
